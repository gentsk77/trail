import { createReadStream } from "node:fs";
import { readdir, readFile, stat } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import readline from "node:readline";
import { TASK_MARKER, type ParsedSession, type SessionSummary } from "./types";

/* Tolerant JSONL parsing over the real Claude Code transcript shapes
   (verified 2026-07-15 against the live store, CC v2.1.x):
   - records carry cwd / timestamp / gitBranch / sessionId
   - type "user": message.{role,content}; content items may be tool_result
   - type "assistant": message.content items may be tool_use (Edit/Write/Bash)
   - type "custom-title": { customTitle }
   - type "pr-link": { prUrl, prNumber, prRepository }                     */

type AnyRecord = Record<string, any>;

function textOf(content: unknown): string {
  if (typeof content === "string") return content;
  if (Array.isArray(content)) {
    return content
      .filter((c: AnyRecord) => c && c.type === "text" && typeof c.text === "string")
      .map((c: AnyRecord) => c.text)
      .join("\n");
  }
  return "";
}

function isToolResultMessage(content: unknown): boolean {
  return Array.isArray(content) && content.some((c: AnyRecord) => c?.type === "tool_result");
}

const COMMIT_RESULT = /\[[^\[\]\s]+ ([0-9a-f]{7,40})\]\s*(.*)/;

/* Command wrappers and local-command caveats are session chrome, not the
   operator's ask — never let them stand in as the first prompt (dogfood
   r4.1: "<local-command-caveat>Caveat: ..." was becoming a task title). */
const CHROME_PROMPT = /^\s*(<local-command-caveat>|<command-name>|<local-command-stdout>|Caveat: The messages below were generated by the user)/;

/* Turn state (dogfood r3, the status-lag P0): does the transcript end
   awaiting the operator? The last meaningful record decides — an
   assistant message that is pure text (no tool_use) closed the turn;
   tool calls, tool results, and typed or queued user input mean the
   agent still holds the ball. Chrome records (system, progress,
   summaries) say nothing about the turn. */
function turnVerdict(record: AnyRecord): boolean | undefined {
  if (record.type === "assistant") {
    const content = record.message?.content;
    if (Array.isArray(content) && content.some((c: AnyRecord) => c?.type === "tool_use")) return false;
    return textOf(content) ? true : undefined;
  }
  if (record.type === "user") return false;
  if (record.type === "queue-operation") return false;
  return undefined;
}

/* Tail read for the idle sweep: last chunk only, so 300 sessions stay
   cheap. A torn first line parses as garbage and is skipped. */
export async function readTailAwaiting(file: string, tailBytes = 256 * 1024): Promise<boolean | undefined> {
  const st = await stat(file);
  const start = Math.max(0, st.size - tailBytes);
  const stream = createReadStream(file, { encoding: "utf8", start });
  let data = "";
  for await (const chunk of stream) data += chunk;
  let verdict: boolean | undefined;
  for (const raw of data.split("\n")) {
    const trimmed = raw.trim();
    if (!trimmed) continue;
    try {
      const v = turnVerdict(JSON.parse(trimmed));
      if (v !== undefined) verdict = v;
    } catch {
      /* torn line at the chunk boundary or the live tail */
    }
  }
  return verdict;
}

async function eachLine(file: string, cb: (record: AnyRecord, line: number) => boolean | void): Promise<void> {
  const rl = readline.createInterface({
    input: createReadStream(file, { encoding: "utf8" }),
    crlfDelay: Infinity
  });
  let n = 0;
  for await (const raw of rl) {
    n += 1;
    const trimmed = raw.trim();
    if (!trimmed) continue;
    let record: AnyRecord;
    try {
      record = JSON.parse(trimmed);
    } catch {
      continue; // torn tail line while a session is being appended
    }
    if (cb(record, n) === false) break;
  }
  rl.close();
}

/* Claude Code's friendly session names live in a per-project
   sessions-index.json (written lazily when its own session picker builds
   summaries), entry shape { sessionId, summary, ... }. The transcripts
   themselves carry no summary records. Cached per directory by mtime;
   a missing or torn index reads as absent. */
const indexCache = new Map<string, { mtimeMs: number; titles: Map<string, string> }>();

export async function sessionIndexTitle(dir: string, sessionId: string): Promise<string | undefined> {
  const file = path.join(dir, "sessions-index.json");
  let st;
  try {
    st = await stat(file);
  } catch {
    return undefined;
  }
  let cached = indexCache.get(dir);
  if (!cached || cached.mtimeMs !== st.mtimeMs) {
    const titles = new Map<string, string>();
    try {
      const parsed = JSON.parse(await readFile(file, "utf8"));
      for (const entry of parsed?.entries ?? []) {
        if (typeof entry?.sessionId === "string" && typeof entry?.summary === "string" && entry.summary.trim()) {
          titles.set(entry.sessionId, entry.summary.trim());
        }
      }
    } catch {
      /* mid-write or foreign shape */
    }
    cached = { mtimeMs: st.mtimeMs, titles };
    indexCache.set(dir, cached);
  }
  return cached.titles.get(sessionId);
}

/* The desktop app is the richer name source: it keeps one record per
   session under its own app-data dir (local_*.json with title,
   titleSource auto|user, and cliSessionId pointing at the CLI store's
   jsonl). Read-only, cached per roots-key, rebuilt at most once a
   minute; an absent dir reads as empty. TRAIL_DESKTOP_SESSIONS_ROOT
   overrides the roots (tests point it at fixtures). */
const DESKTOP_TTL_MS = 60_000;
const desktopCache = new Map<string, { at: number; titles: Map<string, string> }>();

function desktopSessionRoots(): string[] {
  const override = process.env.TRAIL_DESKTOP_SESSIONS_ROOT;
  if (override) return [override];
  const home = os.homedir();
  return [
    path.join(process.env.APPDATA ?? path.join(home, "AppData", "Roaming"), "Claude", "claude-code-sessions"),
    path.join(home, "Library", "Application Support", "Claude", "claude-code-sessions")
  ];
}

export async function desktopSessionTitles(): Promise<Map<string, string>> {
  const roots = desktopSessionRoots();
  const key = roots.join(";");
  const cached = desktopCache.get(key);
  if (cached && Date.now() - cached.at < DESKTOP_TTL_MS) return cached.titles;
  const titles = new Map<string, string>();
  for (const root of roots) {
    let entries: string[] = [];
    try {
      entries = (await readdir(root, { recursive: true })) as string[];
    } catch {
      continue; // no desktop app on this machine / platform
    }
    for (const rel of entries) {
      if (!/local_[^\\/]*\.json$/.test(rel)) continue;
      try {
        const record = JSON.parse(await readFile(path.join(root, rel), "utf8"));
        if (typeof record?.cliSessionId === "string" && typeof record?.title === "string" && record.title.trim()) {
          titles.set(record.cliSessionId, record.title.trim());
        }
      } catch {
        /* mid-write or foreign shape */
      }
    }
  }
  desktopCache.set(key, { at: Date.now(), titles });
  return titles;
}

/* Light pass: head of the file until cwd + first prompt are known; mtime
   stands in for last activity so we never read big files twice. */
export async function summarizeSession(file: string, storeDir: string): Promise<SessionSummary> {
  const id = path.basename(file, ".jsonl");
  let projectDir = "";
  let gitBranch: string | undefined;
  let startedAt = "";
  let title: string | undefined;
  let firstPrompt: string | undefined;
  let hasAssistantTurns = false;
  let scanned = 0;

  await eachLine(file, (record, _line) => {
    scanned += 1;
    if (!startedAt && typeof record.timestamp === "string") startedAt = record.timestamp;
    if (!projectDir && typeof record.cwd === "string") projectDir = record.cwd;
    if (!gitBranch && typeof record.gitBranch === "string") gitBranch = record.gitBranch;
    if (record.type === "assistant") hasAssistantTurns = true;
    if (record.type === "custom-title" && typeof record.customTitle === "string") title = record.customTitle;
    if (!firstPrompt && record.type === "user" && !isToolResultMessage(record.message?.content)) {
      const text = textOf(record.message?.content);
      if (text && !CHROME_PROMPT.test(text)) firstPrompt = text;
    }
    if (!firstPrompt && record.type === "queue-operation" && record.operation === "enqueue" && typeof record.content === "string" && !CHROME_PROMPT.test(record.content)) {
      firstPrompt = record.content;
    }
    /* stop early once the essentials are in hand — but never before the
       first assistant record: a stillborn (queued prompt, no reply) must
       read as such, and it is short by construction */
    if (hasAssistantTurns && projectDir && firstPrompt && startedAt && scanned > 5 && title) return false;
    if (hasAssistantTurns && projectDir && firstPrompt && startedAt && scanned > 120) return false;
  });

  const st = await stat(file);
  const markerTaskId = firstPrompt?.match(TASK_MARKER)?.[1];
  /* name precedence: an explicit custom-title record, then the desktop
     app's title (the sidebar's friendly names, auto or renamed), then
     the CLI picker's index summary; the first prompt stays the
     downstream fallback */
  if (!title) title = (await desktopSessionTitles()).get(id);
  if (!title) title = await sessionIndexTitle(path.dirname(file), id);
  return {
    id, file, storeDir, projectDir, gitBranch,
    startedAt: startedAt || st.birthtime.toISOString(),
    lastActiveAt: st.mtime.toISOString(),
    title, firstPrompt, markerTaskId, hasAssistantTurns
  };
}

/* Full pass: everything the harvester consumes, with line pointers. */
export async function parseSession(file: string, storeDir: string): Promise<ParsedSession> {
  const summary = await summarizeSession(file, storeDir);
  const fileRefs: ParsedSession["fileRefs"] = [];
  const commits: ParsedSession["commits"] = [];
  const prLinks: ParsedSession["prLinks"] = [];
  const userPrompts: ParsedSession["userPrompts"] = [];
  let lastAssistantText: string | undefined;
  let pendingCommitCmd = false;
  let eventCount = 0;
  let awaitingInput = false;

  await eachLine(file, (record, line) => {
    eventCount += 1;
    const verdict = turnVerdict(record);
    if (verdict !== undefined) awaitingInput = verdict;
    if (record.type === "assistant") {
      const text = textOf(record.message?.content);
      if (text) lastAssistantText = text;
      const content = record.message?.content;
      if (Array.isArray(content)) {
        for (const item of content) {
          if (item?.type !== "tool_use") continue;
          const input = item.input ?? {};
          if ((item.name === "Edit" || item.name === "Write") && typeof input.file_path === "string") {
            fileRefs.push({ path: input.file_path, tool: item.name, line });
          } else if (item.name === "Bash" && typeof input.command === "string" && /git commit/.test(input.command)) {
            pendingCommitCmd = true;
          }
        }
      }
    } else if (record.type === "user") {
      const content = record.message?.content;
      if (isToolResultMessage(content)) {
        if (pendingCommitCmd && Array.isArray(content)) {
          for (const item of content) {
            if (item?.type !== "tool_result") continue;
            const text = typeof item.content === "string" ? item.content : textOf(item.content);
            const match = text.match(COMMIT_RESULT);
            if (match) {
              commits.push({ sha: match[1], subject: match[2]?.trim() || undefined, line });
              pendingCommitCmd = false;
            }
          }
        }
      } else {
        const text = textOf(content);
        if (text) userPrompts.push({ text, line });
      }
    } else if (record.type === "pr-link" && typeof record.prUrl === "string") {
      prLinks.push({ url: record.prUrl, number: record.prNumber, repo: record.prRepository, line });
    }
  });

  return { ...summary, fileRefs, commits, prLinks, userPrompts, lastAssistantText, eventCount, awaitingInput };
}
