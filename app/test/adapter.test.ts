import { mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { appendFileSync } from "node:fs";
import { LiveSessionSource } from "../server/adapters/sessions/live";
import { readTailAwaiting } from "../server/adapters/sessions/parse";
import { liveStatusFrom } from "../server/adapters/sessions/types";
import { fixtureSession } from "./fixtures";

let root: string;
let source: LiveSessionSource;

beforeEach(() => {
  root = mkdtempSync(path.join(tmpdir(), "trail-sessions-"));
  const dirA = path.join(root, "D--Repo-alpha");
  mkdirSync(dirA);
  writeFileSync(
    path.join(dirA, "aaaa1111-0000-0000-0000-000000000001.jsonl"),
    fixtureSession({
      sessionId: "aaaa1111-0000-0000-0000-000000000001",
      cwd: "D:\\Repo\\alpha",
      firstPrompt: "fix the flaky test in ci",
      title: "Flaky CI fix",
      editPath: "D:\\Repo\\alpha\\src\\ci.ts",
      commit: { sha: "abc1234", subject: "fix: stabilize ci" },
      pr: { url: "https://github.com/x/y/pull/9", number: 9 }
    })
  );
  writeFileSync(
    path.join(dirA, "aaaa1111-0000-0000-0000-000000000002.jsonl"),
    fixtureSession({
      sessionId: "aaaa1111-0000-0000-0000-000000000002",
      cwd: "D:\\Repo\\alpha",
      firstPrompt: "Work the task brief. [trail-task:11112222-3333-4444-5555-666677778888]"
    })
  );
  source = new LiveSessionSource(root);
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe("live sessions adapter", () => {
  it("lists project dirs with the real path decoded from cwd", async () => {
    const projects = await source.listProjects();
    expect(projects).toHaveLength(1);
    expect(projects[0].storeDir).toBe("D--Repo-alpha");
    expect(projects[0].projectDir).toBe("D:\\Repo\\alpha");
    expect(projects[0].sessionFiles).toHaveLength(2);
  });

  it("summarizes sessions: title, first prompt, dispatch marker", async () => {
    const sessions = await source.listSessions("D--Repo-alpha");
    const bare = sessions.find((s) => s.id.endsWith("1"));
    const marked = sessions.find((s) => s.id.endsWith("2"));
    expect(bare?.title).toBe("Flaky CI fix");
    expect(bare?.firstPrompt).toContain("flaky test");
    expect(bare?.markerTaskId).toBeUndefined();
    expect(marked?.markerTaskId).toBe("11112222-3333-4444-5555-666677778888");
  });

  it("command-wrapper chrome never becomes the first prompt (dogfood r4.1)", async () => {
    const id = "aaaa1111-0000-0000-0000-000000000003";
    const base = { sessionId: id, cwd: "D:\\Repo\\alpha", timestamp: "2026-07-15T08:00:00.000Z" };
    writeFileSync(
      path.join(root, "D--Repo-alpha", `${id}.jsonl`),
      [
        JSON.stringify({ type: "user", ...base, message: { role: "user", content: "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>" } }),
        JSON.stringify({ type: "user", ...base, message: { role: "user", content: "the real ask" } })
      ].join("\n")
    );
    const sessions = await source.listSessions("D--Repo-alpha");
    expect(sessions.find((s) => s.id === id)?.firstPrompt).toBe("the real ask");
  });

  it("desktop-app titles backfill by cliSessionId; custom titles outrank them (dogfood r4)", async () => {
    const desktopRoot = path.join(root, "desktop-store");
    mkdirSync(path.join(desktopRoot, "install", "user"), { recursive: true });
    writeFileSync(
      path.join(desktopRoot, "install", "user", "local_abc.json"),
      JSON.stringify({ sessionId: "local_abc", cliSessionId: "aaaa1111-0000-0000-0000-000000000002", title: "Desktop friendly name", titleSource: "auto" })
    );
    writeFileSync(
      path.join(desktopRoot, "install", "user", "local_def.json"),
      JSON.stringify({ sessionId: "local_def", cliSessionId: "aaaa1111-0000-0000-0000-000000000001", title: "Desktop name loses to custom", titleSource: "auto" })
    );
    const prev = process.env.TRAIL_DESKTOP_SESSIONS_ROOT;
    process.env.TRAIL_DESKTOP_SESSIONS_ROOT = desktopRoot;
    try {
      const sessions = await source.listSessions("D--Repo-alpha");
      expect(sessions.find((s) => s.id.endsWith("2"))?.title).toBe("Desktop friendly name");
      expect(sessions.find((s) => s.id.endsWith("1"))?.title).toBe("Flaky CI fix"); // explicit custom-title wins
    } finally {
      process.env.TRAIL_DESKTOP_SESSIONS_ROOT = prev;
    }
  });

  it("friendly names come from sessions-index.json; custom titles outrank it (dogfood r4)", async () => {
    writeFileSync(
      path.join(root, "D--Repo-alpha", "sessions-index.json"),
      JSON.stringify({
        version: 1,
        entries: [
          { sessionId: "aaaa1111-0000-0000-0000-000000000001", summary: "Index name loses to custom" },
          { sessionId: "aaaa1111-0000-0000-0000-000000000002", summary: "Task brief work session" }
        ]
      })
    );
    const sessions = await source.listSessions("D--Repo-alpha");
    const custom = sessions.find((s) => s.id.endsWith("1"));
    const indexed = sessions.find((s) => s.id.endsWith("2"));
    expect(custom?.title).toBe("Flaky CI fix"); // explicit custom-title wins
    expect(indexed?.title).toBe("Task brief work session"); // index summary backfills
  });

  it("full-parses tool refs, commits, pr links with line pointers", async () => {
    const projects = await source.listProjects();
    const file = projects[0].sessionFiles.find((f) => f.endsWith("1.jsonl"))!;
    const parsed = await source.readSession(file);
    expect(parsed.fileRefs).toEqual([{ path: "D:\\Repo\\alpha\\src\\ci.ts", tool: "Edit", line: 4 }]);
    expect(parsed.commits).toEqual([{ sha: "abc1234", subject: "fix: stabilize ci", line: 6 }]);
    expect(parsed.prLinks[0]).toMatchObject({ url: "https://github.com/x/y/pull/9", number: 9 });
    expect(parsed.lastAssistantText).toContain("Shipped");
  });

  it("never writes under the store root", async () => {
    const before = readdirSync(path.join(root, "D--Repo-alpha")).sort();
    await source.listProjects();
    const file = (await source.listProjects())[0].sessionFiles[0];
    await source.readSession(file);
    expect(readdirSync(path.join(root, "D--Repo-alpha")).sort()).toEqual(before);
  });

  it("live status heuristic steps running -> waiting -> closed", () => {
    const now = Date.parse("2026-07-15T12:00:00Z");
    expect(liveStatusFrom("2026-07-15T11:59:00Z", undefined, now)).toBe("running");
    expect(liveStatusFrom("2026-07-15T11:40:00Z", undefined, now)).toBe("waiting");
    expect(liveStatusFrom("2026-07-15T11:00:00Z", undefined, now)).toBe("closed");
  });

  it("turn state: final text turn awaits input; trailing tool work does not (dogfood r3)", async () => {
    const file = (await source.listProjects())[0].sessionFiles.find((f) => f.endsWith("1.jsonl"))!;
    expect((await source.readSession(file)).awaitingInput).toBe(true);
    expect(await readTailAwaiting(file)).toBe(true);
    /* agent picks tools back up: the turn is open again */
    appendFileSync(file, JSON.stringify({
      type: "assistant", sessionId: "aaaa1111-0000-0000-0000-000000000001",
      message: { role: "assistant", content: [{ type: "tool_use", id: "t9", name: "Bash", input: { command: "npm test" } }] }
    }) + "\n");
    expect((await source.readSession(file)).awaitingInput).toBe(false);
    expect(await readTailAwaiting(file)).toBe(false);
    /* a typed prompt also hands the ball back to the agent */
    appendFileSync(file, JSON.stringify({
      type: "user", sessionId: "aaaa1111-0000-0000-0000-000000000001",
      message: { role: "user", content: "and fix the lint too" }
    }) + "\n");
    expect(await readTailAwaiting(file)).toBe(false);
  });

  it("a completed assistant turn is waiting immediately, no 90s grace (dogfood r3)", () => {
    const now = Date.parse("2026-07-15T12:00:00Z");
    expect(liveStatusFrom("2026-07-15T11:59:59Z", true, now)).toBe("waiting");
    expect(liveStatusFrom("2026-07-15T11:59:59Z", false, now)).toBe("running");
    /* long-idle still closes regardless of turn state */
    expect(liveStatusFrom("2026-07-15T11:00:00Z", true, now)).toBe("closed");
  });
});
